# usage: python3 movedoc.py old_id new_id   (ids like nomaubl/sync/watched-folders)
# Moves the EN and FR file (git mv), rewrites relative links in every NomaUBL page,
# updates sidebars.ts and adds a client redirect in docusaurus.config.ts.
# Absolute links (/nomaubl/...) in JSX/src are NOT rewritten: grep them after.
# zsh: call it once per page, never through a "for p in 'a b'" loop.
import os,re,sys,glob,subprocess,posixpath as pp
os.chdir("/Users/franckblettner/Documents/Tools/GithubProjects/fblettner.github.io")
old,new=sys.argv[1],sys.argv[2]
ROOTS=["docs","i18n/fr/docusaurus-plugin-content-docs/current"]
def ext(root,i):
    for e in (".md",".mdx"):
        if os.path.exists(f"{root}/{i}{e}"): return e
ex=ext("docs",old)
for r in ROOTS:
    os.makedirs(os.path.dirname(f"{r}/{new}"),exist_ok=True)
    subprocess.run(["git","mv",f"{r}/{old}{ex}",f"{r}/{new}{ex}"],check=True)
LINK=re.compile(r"(\]\()([^)#\s]+?\.mdx?)(#[^)\s]*)?(\))")
for r in ROOTS:
    for p in glob.glob(r+"/nomaubl/**/*.md*",recursive=True):
        rel=os.path.relpath(p,r)[:-len(os.path.splitext(p)[1])]   # current id
        was=old if rel==new else rel                              # id before move
        s=open(p).read()
        def fix(m):
            tgt=m.group(2)
            if tgt.startswith(("http","/")): return m.group(0)
            absid=pp.normpath(pp.join(pp.dirname(was),tgt))
            e=os.path.splitext(absid)[1]; absid=absid[:-len(e)]
            if absid==old: absid=new
            if rel==new or absid==new:
                t=pp.relpath(absid,pp.dirname(rel))+e
                if not t.startswith("."): t="./"+t if "/" not in t else t
                return m.group(1)+t+(m.group(3) or "")+m.group(4)
            return m.group(0)
        n=LINK.sub(fix,s)
        if n!=s: open(p,"w").write(n)
# sidebar and redirects (llms files are regenerated by the build)
s=open("sidebars.ts").read().replace(f"'{old}'",f"'{new}'"); open("sidebars.ts","w").write(s)
c=open("docusaurus.config.ts").read()
c=c.replace(f"to: '/{old}'}}",f"to: '/{new}'}}")
line=f"          {{from: '/{old}', to: '/{new}'}},\n"
c=c.replace("        redirects: [\n","        redirects: [\n"+line,1)
open("docusaurus.config.ts","w").write(c)
print("moved",old,"->",new)
